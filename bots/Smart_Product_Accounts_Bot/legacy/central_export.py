
from __future__ import annotations

from datetime import datetime
from pathlib import Path
from typing import Any
from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

HEADER_FILL = PatternFill("solid", fgColor="17324D")
SECTION_FILL = PatternFill("solid", fgColor="0F8B8D")
LIGHT_FILL = PatternFill("solid", fgColor="EAF2F8")
GREEN_FILL = PatternFill("solid", fgColor="DDF3E4")
WHITE_FONT = Font(color="FFFFFF", bold=True)
THIN = Side(style="thin", color="C7D4DE")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
MONEY = '৳#,##0.00;[Red]-৳#,##0.00'

def add_metadata(wb: Workbook, *, bot_name: str, bot_version: str, month: str,
                 generated_by: str, total_records: int) -> None:
    ws = wb.create_sheet("Metadata", 0)
    rows = [
        ("Bot Name", bot_name),
        ("Bot Version", bot_version),
        ("Company", "BURAQ"),
        ("Export Type", "Central Export"),
        ("Schema Version", "1.0"),
        ("Export Month", month),
        ("Generated At", datetime.now().strftime("%Y-%m-%d %H:%M:%S")),
        ("Generated By", generated_by),
        ("Total Records", total_records),
    ]
    ws.append(["Field", "Value"])
    for row in rows:
        ws.append(row)
    style_table(ws)

def style_table(ws, money_columns: tuple[str, ...] = ()) -> None:
    ws.sheet_view.showGridLines = False
    ws.freeze_panes = "A2"
    for cell in ws[1]:
        cell.fill = HEADER_FILL
        cell.font = WHITE_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center")
        cell.border = BORDER
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.border = BORDER
            cell.alignment = Alignment(vertical="center")
    for col in money_columns:
        for cell in ws[col][1:]:
            cell.number_format = MONEY
    for column in ws.columns:
        letter = get_column_letter(column[0].column)
        width = max((len(str(c.value or "")) for c in column), default=10) + 3
        ws.column_dimensions[letter].width = min(max(width, 12), 38)
    if ws.max_row >= 1 and ws.max_column >= 1:
        ws.auto_filter.ref = ws.dimensions

def append_summary(ws, rows: list[tuple[str, Any, str]]) -> None:
    ws.append(["Metric", "Value", "Meaning"])
    for metric, value, meaning in rows:
        ws.append([metric, value, meaning])
    style_table(ws)
    for r in range(2, ws.max_row + 1):
        metric = str(ws.cell(r, 1).value or "")
        if any(x in metric for x in ("Amount", "COD", "Charge", "Payout", "Settlement", "Due", "Expense", "Payment", "Balance")):
            ws.cell(r, 2).number_format = MONEY

from database import all_orders
from settlement import available_settlement_months, settlement_summary

def build_smart_central_export(output: Path, month: str | None = None, generated_by: str = "Admin") -> Path:
    months = available_settlement_months(limit=120)
    if not months:
        raise ValueError("কোনো Deliveries/Settlement data পাওয়া যায়নি।")
    target = month or f"{months[0][0]:04d}-{months[0][1]:02d}"
    year, mon = map(int, target.split("-"))
    summary = settlement_summary(year, mon)
    orders = [dict(r) for r in all_orders() if str(r["order_date"] or "").startswith(target)]

    wb = Workbook()
    default = wb.active
    wb.remove(default)
    add_metadata(
        wb, bot_name="Smart Product Accounts Bot", bot_version="9.0",
        month=target, generated_by=generated_by, total_records=len(orders),
    )

    ws = wb.create_sheet("Summary")
    append_summary(ws, [
        ("Month", target, "Selected accounting month"),
        ("Total Parcel", summary["total_parcels"], "Deliveries CSV parcel count"),
        ("Delivered Parcel", summary["delivered_parcels"], "Matched delivery invoice"),
        ("Returned Parcel", summary["return_parcels"], "Matched return invoice"),
        ("Pending Parcel", summary["pending_parcels"], "Not yet matched"),
        ("Total COD", summary["total_cod"], "All imported COD"),
        ("Return COD", summary["return_cod"], "Returned parcel COD"),
        ("Courier Charge", summary["total_charge"], "Matched courier charge"),
        ("Expected Settlement", summary["expected_settlement"], "COD − Return COD − Charge"),
        ("Payout / Collected", summary["matched_payout"], "Matched paid invoice payout"),
        ("Remaining Due", summary["remaining"], "Expected − Payout"),
    ])

    sws = wb.create_sheet("Settlement")
    headers = [
        "Month","Total Parcel","Total COD","Delivered Parcel","Delivered COD",
        "Returned Parcel","Return COD","Pending Parcel","Pending COD",
        "Courier Charge","Expected Settlement","Payout / Collected","Remaining Due"
    ]
    sws.append(headers)
    sws.append([
        target, summary["total_parcels"], summary["total_cod"],
        summary["delivered_parcels"], summary["delivered_cod"],
        summary["return_parcels"], summary["return_cod"],
        summary["pending_parcels"], summary["pending_cod"],
        summary["total_charge"], summary["expected_settlement"],
        summary["matched_payout"], summary["remaining"],
    ])
    style_table(sws, money_columns=("C","E","G","I","J","K","L","M"))

    pws = wb.create_sheet("Product Summary")
    pws.append(["Month","Product","Delivered","Returned","Pending","Total Parcel"])
    for item in summary.get("products") or []:
        pws.append([
            target, item["product"], item["delivered"], item["returned"],
            item["pending"], int(item["delivered"])+int(item["returned"])+int(item["pending"])
        ])
    style_table(pws)

    ows = wb.create_sheet("Courier Orders")
    ows.append(["ID","Date","Product","COD","Consignment ID","Merchant Order ID","Description","Source File","Imported At"])
    for r in orders:
        ows.append([
            r.get("id"), r.get("order_date"), r.get("product"), r.get("cod"),
            r.get("consignment"), r.get("merchant_id"), r.get("description"),
            r.get("source_file"), r.get("imported_at"),
        ])
    style_table(ows, money_columns=("D",))

    wb.save(output)
    return output
