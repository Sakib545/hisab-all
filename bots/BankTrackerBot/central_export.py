
from __future__ import annotations

from datetime import datetime
from pathlib import Path
from typing import Any
from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

HEADER_FILL = PatternFill("solid", fgColor="17324D")
SECTION_FILL = PatternFill("solid", fgColor="0F8B8D")
LIGHT_FILL = PatternFill("solid", fgColor="EAF2F8")
GREEN_FILL = PatternFill("solid", fgColor="DDF3E4")
WHITE_FONT = Font(color="FFFFFF", bold=True)
THIN = Side(style="thin", color="C7D4DE")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
MONEY = '৳#,##0.00;[Red]-৳#,##0.00'

def add_metadata(wb: Workbook, *, bot_name: str, bot_version: str, month: str,
                 generated_by: str, total_records: int) -> None:
    ws = wb.create_sheet("Metadata", 0)
    rows = [
        ("Bot Name", bot_name),
        ("Bot Version", bot_version),
        ("Company", "BURAQ"),
        ("Export Type", "Central Export"),
        ("Schema Version", "1.0"),
        ("Export Month", month),
        ("Generated At", datetime.now().strftime("%Y-%m-%d %H:%M:%S")),
        ("Generated By", generated_by),
        ("Total Records", total_records),
    ]
    ws.append(["Field", "Value"])
    for row in rows:
        ws.append(row)
    style_table(ws)

def style_table(ws, money_columns: tuple[str, ...] = ()) -> None:
    ws.sheet_view.showGridLines = False
    ws.freeze_panes = "A2"
    for cell in ws[1]:
        cell.fill = HEADER_FILL
        cell.font = WHITE_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center")
        cell.border = BORDER
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.border = BORDER
            cell.alignment = Alignment(vertical="center")
    for col in money_columns:
        for cell in ws[col][1:]:
            cell.number_format = MONEY
    for column in ws.columns:
        letter = get_column_letter(column[0].column)
        width = max((len(str(c.value or "")) for c in column), default=10) + 3
        ws.column_dimensions[letter].width = min(max(width, 12), 38)
    if ws.max_row >= 1 and ws.max_column >= 1:
        ws.auto_filter.ref = ws.dimensions

def append_summary(ws, rows: list[tuple[str, Any, str]]) -> None:
    ws.append(["Metric", "Value", "Meaning"])
    for metric, value, meaning in rows:
        ws.append([metric, value, meaning])
    style_table(ws)
    for r in range(2, ws.max_row + 1):
        metric = str(ws.cell(r, 1).value or "")
        if any(x in metric for x in ("Amount", "COD", "Charge", "Payout", "Settlement", "Due", "Expense", "Payment", "Balance")):
            ws.cell(r, 2).number_format = MONEY

from database import rows_for_month

def build_bank_central_export(output: Path, month: str, generated_by: str = "Admin") -> Path:
    rows = [dict(r) for r in rows_for_month(month)]
    total = sum(float(r.get("amount") or 0) for r in rows)
    largest = max((float(r.get("amount") or 0) for r in rows), default=0)
    average = total / len(rows) if rows else 0

    wb = Workbook()
    wb.remove(wb.active)
    add_metadata(
        wb, bot_name="BankTrackerBot", bot_version="7.1",
        month=month, generated_by=generated_by, total_records=len(rows),
    )
    ws = wb.create_sheet("Summary")
    append_summary(ws, [
        ("Month", month, "Selected accounting month"),
        ("Dollar Payment", total, "Monthly outgoing bank payments"),
        ("Transaction Count", len(rows), "Matched transactions"),
        ("Average Payment", average, "Total ÷ transactions"),
        ("Largest Payment", largest, "Highest transaction"),
    ])

    tws = wb.create_sheet("Transactions")
    headers = [
        "ID","Payment ID","Bank/MFS","Receiver","Account","Amount",
        "Date","Time","Reference","Remarks","Created"
    ]
    tws.append(headers)
    for r in rows:
        tws.append([
            r.get("id"), r.get("payment_code"), r.get("bank_name"),
            r.get("receiver_name"), r.get("account_number"), r.get("amount"),
            r.get("transaction_date"), r.get("transaction_time"),
            r.get("reference_id"), r.get("remarks"), r.get("created_at"),
        ])
    style_table(tws, money_columns=("F",))

    mws = wb.create_sheet("Monthly Summary")
    mws.append(["Month","Transaction Count","Dollar Payment"])
    mws.append([month, len(rows), total])
    style_table(mws, money_columns=("C",))
    wb.save(output)
    return output
